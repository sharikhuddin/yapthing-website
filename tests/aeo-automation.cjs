'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const report=JSON.parse(read('seo/aeo-report.json')),queue=JSON.parse(read('seo/aeo-opportunities.json')),manifest=JSON.parse(read('search-manifest.json'));
assert.equal(report.kind,'offline-answer-engine-readiness');
assert.equal(report.trackedPages,manifest.pages.length);
assert.equal(report.pages.length,manifest.pages.length);
assert.equal(report.criticalPages,0,'No critical AEO errors in public pages');
assert(report.crawlerRules['OAI-SearchBot'].robotsAllowed,'ChatGPT search crawler permitted by robots');
assert(report.crawlerRules.Googlebot.robotsAllowed,'Googlebot permitted by robots');
assert(report.robotsSitemap,'Sitemap declared in robots.txt');
assert.equal(queue.kind,'aeo-editorial-review');
assert(queue.suggestions.every(x=>x.approval==='required'),'Editorial changes require review');
assert(queue.items.every(x=>x.action.includes('Human editorial review')),'Automation cannot manufacture publishable content');
for(const page of report.pages){
 const manifestPage=manifest.pages.find(x=>x.url===page.url);
 assert(manifestPage,'AEO page missing from canonical sitemap '+page.url);
 assert.equal(page.lastmod,manifestPage.lastmod);
 const html=read(manifestPage.file);
 assert(html.includes('rel="canonical" href="'+page.url+'"'),'AEO canonical mismatch '+page.url);
 assert(Array.isArray(page.findings));
 assert(!page.findings.some(x=>x.priority==='critical'),'Critical structural issue '+page.url);
}
const source=read('scripts/aeo-readiness.cjs');
assert(source.includes("JSON.parse(match[1])"),'Structured-data validation included');
assert(source.includes("faq_visibility"),'FAQ schema must agree with visible content');
assert(source.includes("robotsAllowed"),'Crawler access check present');
assert(!/openai\s*api\s*key|gemini\s*api\s*key/i.test(source),'No model API key required');
const guide=read('guides/index.html');
assert(guide.includes('id="yap-quick-answers"'),'Real visible quick-answer guide');
assert((guide.match(/<h3>/g)||[]).length>=6,'At least six verified answer-first sections');
const html=read('admin/index.html');
assert(html.includes('id="aeo-intelligence"'),'AEO admin section');
assert(html.includes('href="#aeo-intelligence"'),'AEO admin navigation');
assert(html.includes('/assets/admin-aeo-readiness.js'));
assert(html.includes('id="panel" hidden'),'Admin section cannot bypass authentication');
const workflow=read('.github/workflows/seo-marketing-maintenance.yml');
for(const filename of ['scripts/aeo-readiness.cjs','tests/aeo-automation.cjs','seo/aeo-report.json','seo/aeo-opportunities.json'])assert(workflow.includes(filename),'Maintenance workflow missing '+filename);
const before=read('seo/aeo-report.json')+read('seo/aeo-opportunities.json');
cp.execFileSync(process.execPath,[path.join(root,'scripts/aeo-readiness.cjs')],{cwd:root,stdio:'pipe'});
assert.equal(before,read('seo/aeo-report.json')+read('seo/aeo-opportunities.json'),'AEO reports must be stable across unchanged runs');
console.log('PASS AEO: '+report.trackedPages+' pages, 0 critical, robots permissions, factual schema, human review, static audit, deterministic scheduled reports');
